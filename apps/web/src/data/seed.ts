function opportunityEvidence(
  id: string,
  label: string,
  source: string,
  excerpt: string,
  state: EvidenceReference['state'] = 'source-verified',
): EvidenceReference {
  return {
    id,
    label,
    source,
    excerpt,
    state,
    observedAt: '28 Aug 2026',
  };
}

